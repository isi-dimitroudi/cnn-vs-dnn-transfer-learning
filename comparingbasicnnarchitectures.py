import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import keras
from keras.models import Sequential
from keras.layers import Dense, Dropout, Flatten, Conv2D, MaxPooling2D

results_data = []

def create_cnn():
    model = Sequential([
        keras.Input(shape=(28, 28, 1)),
        Conv2D(6, kernel_size=(3, 3), activation='relu'),
        MaxPooling2D(pool_size=(2, 2)),
        Conv2D(12, kernel_size=(3, 3), activation='relu'),
        MaxPooling2D(pool_size=(2, 2)),
        Flatten(),
        Dense(128, activation='relu'),
        Dropout(0.5),
        Dense(10, activation='softmax')
    ])
    model.compile(loss='categorical_crossentropy', optimizer='Adam', metrics=['accuracy'])
    return model

def create_dnn():
    model = Sequential([
        keras.Input(shape=(28, 28, 1)),
        Flatten(),
        Dense(128, activation='relu'),
        Dense(64, activation='relu'),
        Dropout(0.5),
        Dense(10, activation='softmax')
    ])
    model.compile(loss='categorical_crossentropy', optimizer='Adam', metrics=['accuracy'])
    return model

skf = StratifiedKFold(n_splits=6, shuffle=True, random_state=42)
y_train_labels = np.argmax(y_train, axis=1)

for fold_idx, (train_index, val_index) in enumerate(skf.split(x_train_cnn, y_train_labels)):
    print(f"\n--- Fold {fold_idx + 1} ---")
    X_fold_train, X_fold_val = x_train_cnn[train_index], x_train_cnn[val_index]
    Y_fold_train, Y_fold_val = y_train[train_index], y_train[val_index]

    for name, create_func in [('CNN', create_cnn), ('DNN', create_dnn)]:
        print(f"Training {name}...")
        model = create_func()
        history = model.fit(X_fold_train, Y_fold_train, validation_data=(X_fold_val, Y_fold_val),
                            epochs=10, batch_size=125, verbose=0)

        print(f"{name} Final - Loss: {history.history['loss'][-1]:.4f}, Val Loss: {history.history['val_loss'][-1]:.4f}")

        plt.figure(figsize=(6, 4))
        plt.plot(history.history['loss'], label='Train Loss')
        plt.plot(history.history['val_loss'], label='Val Loss')
        plt.title(f'{name} - Fold {fold_idx + 1} Loss')
        plt.legend()
        plt.show()

        sets = [('Train', X_fold_train, Y_fold_train), ('Test', x_test_cnn, y_test)]
        for set_name, X_eval, Y_eval in sets:
            preds = np.argmax(model.predict(X_eval, verbose=0), axis=1)
            true = np.argmax(Y_eval, axis=1)

            results_data.append({
                'Technique name': name,
                'Set': set_name,
                'Fold number': fold_idx + 1,
                'Accuracy': accuracy_score(true, preds),
                'Precision': precision_score(true, preds, average='macro', zero_division=0),
                'Recall': recall_score(true, preds, average='macro', zero_division=0),
                'F1 score': f1_score(true, preds, average='macro', zero_division=0)
            })

df_results = pd.DataFrame(results_data)
df_results.to_csv('erotima1.csv', index=False)

