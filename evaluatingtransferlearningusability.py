import matplotlib.pyplot as plt

def plot_learning_curves(history, model_name="Μοντέλο"):
    """
    Σχεδιάζει τις καμπύλες Accuracy και Loss για τα δεδομένα εκπαίδευσης και επικύρωσης.
    """
    # Εξαγωγή δεδομένων από το history object
    acc = history.history.get('accuracy') or history.history.get('acc')
    val_acc = history.history.get('val_accuracy') or history.history.get('val_acc')
    loss = history.history.get('loss')
    val_loss = history.history.get('val_loss')

    epochs = range(1, len(acc) + 1)

    # Δημιουργία καμβά με 2 υπογραφήματα (1 γραμμή, 2 στήλες)
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))

    # --- 1. Καμπύλη Ακρίβειας (Accuracy) ---
    ax1.plot(epochs, acc, 'b-', label='Training Accuracy', linewidth=2)
    ax1.plot(epochs, val_acc, 'r-', label='Validation Accuracy', linewidth=2)
    ax1.set_title(f'{model_name}: Καμπύλη Ακρίβειας', fontsize=14)
    ax1.set_xlabel('Εποχές', fontsize=12)
    ax1.set_ylabel('Ακρίβεια', fontsize=12)
    ax1.legend(loc='lower right')
    ax1.grid(True, linestyle='--', alpha=0.7)

    # --- 2. Καμπύλη Απώλειας (Loss) ---
    ax2.plot(epochs, loss, 'b-', label='Training Loss', linewidth=2)
    ax2.plot(epochs, val_loss, 'r-', label='Validation Loss', linewidth=2)
    ax2.set_title(f'{model_name}: Καμπύλη Απώλειας', fontsize=14)
    ax2.set_xlabel('Εποχές', fontsize=12)
    ax2.set_ylabel('Απώλεια (Loss)', fontsize=12)
    ax2.legend(loc='upper right')
    ax2.grid(True, linestyle='--', alpha=0.7)

    # Προσαρμογή διάταξης και αποθήκευση/εμφάνιση
    plt.tight_layout()

    # Προαιρετικά: Αποθήκευση της εικόνας για την αναφορά
    filename = f"{model_name.replace(' ', '_')}_learning_curves.png"
    plt.savefig(filename, dpi=300, bbox_inches='tight')

    plt.show()

import matplotlib.pyplot as plt
import keras

def auto_plot_histories():
    found_any = False
    for var_name, obj in list(globals().items()):
        history_dict = None

        # Check if the object is a Keras History object
        if isinstance(obj, keras.callbacks.History) and hasattr(obj, 'history'):
            history_dict = obj.history
        # Check if it's a model that has a .history attribute from a recent .fit() call
        elif hasattr(obj, 'history') and isinstance(getattr(obj, 'history'), dict):
            history_dict = obj.history
        # Also handle cases where 'history' is just a dictionary (returned by some wrappers)
        elif isinstance(obj, dict) and ('accuracy' in obj or 'acc' in obj) and 'loss' in obj:
            history_dict = obj

        if history_dict:
            found_any = True
            acc = history_dict.get('accuracy') or history_dict.get('acc')
            val_acc = history_dict.get('val_accuracy') or history_dict.get('val_acc')
            loss = history_dict.get('loss')
            val_loss = history_dict.get('val_loss')

            if acc and loss:
                epochs = range(1, len(acc) + 1)
                fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))

                # Accuracy Plot
                ax1.plot(epochs, acc, 'b-', label='Train Acc')
                if val_acc:
                    ax1.plot(epochs, val_acc, 'r-', label='Val Acc')
                ax1.set_title(f'Accuracy: {var_name}')
                ax1.set_xlabel('Epochs')
                ax1.legend()
                ax1.grid(True)

                # Loss Plot
                ax2.plot(epochs, loss, 'b-', label='Train Loss')
                if val_loss:
                    ax2.plot(epochs, val_loss, 'r-', label='Val Loss')
                ax2.set_title(f'Loss: {var_name}')
                ax2.set_xlabel('Epochs')
                ax2.legend()
                ax2.grid(True)

                plt.tight_layout()
                plt.savefig(f'learning_curves_{var_name}.png', dpi=300)
                plt.show()
                print(f"Plotted and saved: learning_curves_{var_name}.png")

    if not found_any:
        print("No valid Keras History objects or trained models found in global variables.")

