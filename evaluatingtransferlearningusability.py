import numpy as np
import keras
from keras.datasets import fashion_mnist

# Load the data
(x_train, y_train), (x_test, y_test) = fashion_mnist.load_data()

# Normalize the image data
x_train = x_train / 255.0
x_test = x_test / 255.0

# Reshape to include a single color channel
x_train = x_train.reshape(-1, 28, 28, 1)
x_test = x_test.reshape(-1, 28, 28, 1)

# Apply one-hot encoding to the labels
y_train = keras.utils.to_categorical(y_train, 10)
y_test = keras.utils.to_categorical(y_test, 10)

# Print shapes to verify
print(f"x_train shape: {x_train.shape}")
print(f"y_train shape: {y_train.shape}")

from keras.models import Sequential, load_model
from keras.layers import Dense, Dropout, Flatten, Conv2D, MaxPooling2D

def create_cnn_scratch():
    model = Sequential([
        Conv2D(6, (3, 3), activation='relu', input_shape=(28, 28, 1)),
        MaxPooling2D((2, 2)),
        Conv2D(12, (3, 3), activation='relu'),
        MaxPooling2D((2, 2)),
        Flatten(),
        Dense(128, activation='relu'),
        Dropout(0.5),
        Dense(10, activation='softmax')
    ])
    model.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['accuracy'])
    return model

def create_dnn_scratch():
    model = Sequential([
        Flatten(input_shape=(28, 28, 1)),
        Dense(128, activation='relu'),
        Dense(64, activation='relu'),
        Dropout(0.5),
        Dense(10, activation='softmax')
    ])
    model.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['accuracy'])
    return model

def get_transfer_model(filepath):
    # Load the saved .h5 model
    model = load_model(filepath)

    # Freeze all layers except the last one
    for layer in model.layers[:-1]:
        layer.trainable = False
    model.layers[-1].trainable = True

    # Re-compile the model
    model.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['accuracy'])
    return model

# Create the CNN and DNN models from scratch
cnn_model = create_cnn_scratch()
dnn_model = create_dnn_scratch()

# Display model summaries to verify architecture
print("CNN Model Summary:")
cnn_model.summary()

print("\nDNN Model Summary:")
dnn_model.summary()

from sklearn.model_selection import StratifiedKFold
import pandas as pd
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score
import numpy as np

results_data = []
skf = StratifiedKFold(n_splits=6, shuffle=True, random_state=42)

y_train_labels = np.argmax(y_train, axis=1)

fold_idx = 1
for train_index, val_index in skf.split(x_train, y_train_labels):
    print(f"Processing Fold {fold_idx}...")
    X_fold_train, X_fold_val = x_train[train_index], x_train[val_index]
    Y_fold_train, Y_fold_val = y_train[train_index], y_train[val_index]

    # Helper to evaluate and append
    def evaluate_and_append(model, tech_name, fold_num):
        sets = [('Train', X_fold_train, Y_fold_train), ('Test', x_test, y_test)]
        for set_label, x_data, y_true_cat in sets:
            y_pred_cat = model.predict(x_data, verbose=0)
            y_true = np.argmax(y_true_cat, axis=1)
            y_pred = np.argmax(y_pred_cat, axis=1)

            results_data.append({
                'Technique name': tech_name,
                'Set': set_label,
                'Fold number': fold_num,
                'Accuracy': accuracy_score(y_true, y_pred),
                'Precision': precision_score(y_true, y_pred, average='macro'),
                'Recall': recall_score(y_true, y_pred, average='macro'),
                'F1 score': f1_score(y_true, y_pred, average='macro')
            })

    # Model 1: CNN from scratch
    model1 = create_cnn_scratch()
    model1.fit(X_fold_train, Y_fold_train, validation_data=(X_fold_val, Y_fold_val), epochs=150, batch_size=125, verbose=0)
    evaluate_and_append(model1, 'CNN from_scratch', fold_idx)

    # Model 2: DNN from scratch
    model2 = create_dnn_scratch()
    model2.fit(X_fold_train, Y_fold_train, validation_data=(X_fold_val, Y_fold_val), epochs=150, batch_size=125, verbose=0)
    evaluate_and_append(model2, 'DNN from_scratch', fold_idx)

    # Model 3: CNN Transfer
    model3 = get_transfer_model('/content/cnn_model_final.h5')
    model3.fit(X_fold_train, Y_fold_train, validation_data=(X_fold_val, Y_fold_val), epochs=40, batch_size=125, verbose=0)
    model3.trainable = True
    model3.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['accuracy'])
    model3.fit(X_fold_train, Y_fold_train, validation_data=(X_fold_val, Y_fold_val), epochs=20, batch_size=125, verbose=0)
    evaluate_and_append(model3, 'CNN _transfer', fold_idx)

    # Model 4: DNN Transfer
    model4 = get_transfer_model('/content/dnn_model_final.h5')
    model4.fit(X_fold_train, Y_fold_train, validation_data=(X_fold_val, Y_fold_val), epochs=40, batch_size=125, verbose=0)
    model4.trainable = True
    model4.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['accuracy'])
    model4.fit(X_fold_train, Y_fold_train, validation_data=(X_fold_val, Y_fold_val), epochs=20, batch_size=125, verbose=0)
    evaluate_and_append(model4, 'DNN _transfer', fold_idx)

    fold_idx += 1

df_results = pd.DataFrame(results_data)
df_results.to_csv('erotima2.csv', index=False)
